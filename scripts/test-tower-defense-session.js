#!/usr/bin/env node
const assert = require('node:assert/strict');
const S = require('../bonus/vozova-hradba/session.js');
const data = new Map();
const storage = { getItem: key => data.get(key), setItem: (key, value) => data.set(key, value) };
const route = '/bonus/vozova-hradba/';
const profile = S.read(storage, route);
profile.language = 'cs'; profile.seen = ['build', 'hill']; profile.attempts = 1;
S.save(storage, route, profile);
assert.deepEqual(S.read(storage, route + 'index.html'), profile, 'index.html and the directory share progress');
assert.equal(S.read(storage, '/husitske-valky-test' + route).attempts, 0, 'test and production paths have separate records');
assert.equal(data.has('gameLanguage'), false, 'the bonus never writes the main game language');
const won = { outcome: 'won', cleared: 8, camp: 10, kills: 80 };
assert.equal(S.record(profile, won), true);
assert.equal(S.record(profile, { ...won, camp: 9, kills: 100 }), false, 'camp survival outranks kill count');
assert.equal(S.record(profile, { ...won, camp: 9, kills: 1000 }), false, 'even the largest valid kill count cannot outweigh camp survival');
assert.equal(S.record(profile, { outcome: 'lost', cleared: 7, camp: 0, kills: 100 }), false);
assert.equal(S.record(profile, { ...won, camp: 20 }), true);
for (let i = 0; i < 20; i++) S.record(profile, won);
assert.equal(profile.recent.length, 10, 'local history is bounded');
assert.equal(S.record(profile, { ...won, outcome: 'running' }), false);
assert.equal(S.record(profile, { ...won, camp: NaN }), false);
data.set(S.keyFor(route), '{broken');
assert.equal(S.read(storage, route).best, null);
data.set(S.keyFor(route), JSON.stringify({ seen: 'bad', recent: null, best: {}, attempts: -5 }));
assert.deepEqual(S.read(storage, route).seen, []);
assert.equal(S.read(storage, route).attempts, 0);
const blocked = { getItem() { throw new Error('denied'); }, setItem() { throw new Error('denied'); } };
assert.equal(S.read(blocked, route).best, null);
assert.equal(S.save(blocked, route, profile), false, 'blocked storage does not break a run');
const note = 'Příliš těžké <script>…</script>\nRád zkusím znovu.';
const report = JSON.parse(S.report(won, { clarity: 'mixed', replay: 'yes', note }));
assert.equal(report.feedback.note, note, 'free text is preserved as data');
assert.equal(report.feedback.replay, 'yes');
assert.equal(JSON.parse(S.report(won, { note: 'x'.repeat(2000) })).feedback.note.length, 1200);
console.log('✓ Vozová hradba: izolované záznamy, rekordy, opakování, zaučení a kopírovatelné hodnocení');
